-- PostgreSQL schema for TrustVault. The application can also let Hibernate
-- create these tables, but production installs should apply versioned SQL.
CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN', 'OWNER', 'VIEWER'))
);

CREATE TABLE IF NOT EXISTS documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    storage_key VARCHAR(500) NOT NULL UNIQUE,
    owner_id BIGINT NOT NULL REFERENCES app_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS document_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    permission_level VARCHAR(16) NOT NULL CHECK (permission_level IN ('READ', 'EDIT')),
    granted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_document_permission_user UNIQUE (document_id, user_id)
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_email VARCHAR(254) NOT NULL,
    action VARCHAR(50) NOT NULL,
    document_id BIGINT,
    details VARCHAR(1000),
    outcome VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    previous_hash VARCHAR(64),
    entry_hash VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS idx_audit_actor ON audit_logs(actor_email);
CREATE INDEX IF NOT EXISTS idx_audit_document ON audit_logs(document_id);
CREATE INDEX IF NOT EXISTS idx_audit_time ON audit_logs(occurred_at);

CREATE TABLE IF NOT EXISTS audit_chain_head (
    id INTEGER PRIMARY KEY,
    initialized BOOLEAN NOT NULL,
    entry_count BIGINT NOT NULL,
    head_hash VARCHAR(64) NOT NULL,
    last_entry_hash VARCHAR(64) NOT NULL
);
